use crate::theme::{Hex, Theme};

fn theme(name: &str, bg: u32, fg: u32, cursor: u32, selection: u32, ansi: [u32; 16]) -> Theme {
    Theme {
        name: name.into(),
        background: Hex::rgb(bg),
        foreground: Hex::rgb(fg),
        cursor: Hex::rgb(cursor),
        selection: Hex::rgb(selection),
        ansi: ansi.map(Hex::rgb),
    }
}

