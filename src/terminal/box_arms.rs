/// Line weight of one arm of a box-drawing character.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Weight {
    None,
    Light,
    Heavy,
    Double,
}

use Weight::{Double as D, Heavy as H, Light as L, None as N};

/// Arms of a box-drawing character as `[up, down, left, right]`, or `None` for glyphs that
/// are not plain line junctions (rounded corners, diagonals, dashes with gaps are mapped to
/// their solid equivalents).
pub fn arms(c: char) -> Option<[Weight; 4]> {
    Some(match c {
        '─' | '┄' | '┈' | '╌' => [N, N, L, L],
        '━' | '┅' | '┉' | '╍' => [N, N, H, H],
        '│' | '┆' | '┊' | '╎' => [L, L, N, N],
        '┃' | '┇' | '┋' | '╏' => [H, H, N, N],
        '┌' => [N, L, N, L],
        '┍' => [N, L, N, H],
        '┎' => [N, H, N, L],
        '┏' => [N, H, N, H],
        '┐' => [N, L, L, N],
        '┑' => [N, L, H, N],
        '┒' => [N, H, L, N],
        '┓' => [N, H, H, N],
        '└' => [L, N, N, L],
        '┕' => [L, N, N, H],
        '┖' => [H, N, N, L],
        '┗' => [H, N, N, H],
        '┘' => [L, N, L, N],
        '┙' => [L, N, H, N],
        '┚' => [H, N, L, N],
        '┛' => [H, N, H, N],
        '├' => [L, L, N, L],
        '┝' => [L, L, N, H],
        '┞' => [H, L, N, L],
        '┟' => [L, H, N, L],
        '┠' => [H, H, N, L],
        '┡' => [H, L, N, H],
        '┢' => [L, H, N, H],
        '┣' => [H, H, N, H],
        '┤' => [L, L, L, N],
        '┥' => [L, L, H, N],
        '┦' => [H, L, L, N],
        '┧' => [L, H, L, N],
        '┨' => [H, H, L, N],
        '┩' => [H, L, H, N],
        '┪' => [L, H, H, N],
        '┫' => [H, H, H, N],
        '┬' => [N, L, L, L],
        '┭' => [N, L, H, L],
        '┮' => [N, L, L, H],
        '┯' => [N, L, H, H],
        '┰' => [N, H, L, L],
        '┱' => [N, H, H, L],
        '┲' => [N, H, L, H],
        '┳' => [N, H, H, H],
        '┴' => [L, N, L, L],
        '┵' => [L, N, H, L],
        '┶' => [L, N, L, H],
        '┷' => [L, N, H, H],
        '┸' => [H, N, L, L],
        '┹' => [H, N, H, L],
        '┺' => [H, N, L, H],
        '┻' => [H, N, H, H],
        '┼' => [L, L, L, L],
        '┽' => [L, L, H, L],
        '┾' => [L, L, L, H],
        '┿' => [L, L, H, H],
        '╀' => [H, L, L, L],
        '╁' => [L, H, L, L],
        '╂' => [H, H, L, L],
        '╃' => [H, L, H, L],
        '╄' => [H, L, L, H],
        '╅' => [L, H, H, L],
        '╆' => [L, H, L, H],
        '╇' => [H, L, H, H],
        '╈' => [L, H, H, H],
        '╉' => [H, H, H, L],
        '╊' => [H, H, L, H],
        '╋' => [H, H, H, H],
        '═' => [N, N, D, D],
        '║' => [D, D, N, N],
        '╒' => [N, L, N, D],
        '╓' => [N, D, N, L],
        '╔' => [N, D, N, D],
        '╕' => [N, L, D, N],
        '╖' => [N, D, L, N],
        '╗' => [N, D, D, N],
        '╘' => [L, N, N, D],
        '╙' => [D, N, N, L],
        '╚' => [D, N, N, D],
        '╛' => [L, N, D, N],
        '╜' => [D, N, L, N],
        '╝' => [D, N, D, N],
        '╞' => [L, L, N, D],
        '╟' => [D, D, N, L],
        '╠' => [D, D, N, D],
        '╡' => [L, L, D, N],
        '╢' => [D, D, L, N],
        '╣' => [D, D, D, N],
        '╤' => [N, L, D, D],
        '╥' => [N, D, L, L],
        '╦' => [N, D, D, D],
        '╧' => [L, N, D, D],
        '╨' => [D, N, L, L],
        '╩' => [D, N, D, D],
        '╪' => [L, L, D, D],
        '╫' => [D, D, L, L],
        '╬' => [D, D, D, D],
        '╴' => [N, N, L, N],
        '╵' => [L, N, N, N],
        '╶' => [N, N, N, L],
        '╷' => [N, L, N, N],
        '╸' => [N, N, H, N],
        '╹' => [H, N, N, N],
        '╺' => [N, N, N, H],
        '╻' => [N, H, N, N],
        '╼' => [N, N, L, H],
        '╽' => [L, H, N, N],
        '╾' => [N, N, H, L],
        '╿' => [H, L, N, N],
        _ => return None,
    })
}
